[BITS 16]
[ORG 0x7C00]

START:
    MOV AX, 0x0300
    INT 0x10
	
	MOV AX, 0x0100
	MOV CX, 0x2000
	INT 0x10
	
	MOV AX, 0x0200
	XOR DX, DX
	INT 0x10
	
	MOV CX, 0x0050 ; 80 lines
	XOR SI, SI
	
	CALL SHOW_BLUE
	CALL SHOW_PINK
	CALL SHOW_WHITE
	
	SUB SI, 0x0A
	CALL SHOW_PINK
	
	XOR SI, SI
	CALL SHOW_BLUE
	
	CLI
	HLT
	
SHOW_BLUE:
	MOV AX, 0x0920
	MOV BX, 0x00B0
	INT 0x10
	
	INC DH
	
	MOV AX, 0x0200
	INT 0x10
	
	INC SI
	
	CMP SI, 0x05
	JNE SHOW_BLUE
	RET
	
SHOW_PINK:
	MOV AX, 0x0920
	MOV bx, 0x00D0
	int 0x10
	
	INC DH
	
	MOV AX, 0x0200
	INT 0x10
	
	INC SI
	
	CMP SI, 0x0A
	JNE SHOW_PINK
	RET
	
SHOW_WHITE:
	MOV AX, 0x0920
	MOV BX, 0x00F0
	INT 0x10
	
	INC DH
	
	MOV AX, 0x0200
	INT 0x10
	
	INC SI
	
	CMP SI, 0x0F
	JNE SHOW_WHITE
	RET

